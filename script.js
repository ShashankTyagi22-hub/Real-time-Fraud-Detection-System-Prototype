async function login(){

const email =
document.getElementById("email").value;

const password =
document.getElementById("password").value;

const res =
await fetch(
"http://127.0.0.1:5000/login",
{

method:"POST",

headers:{
"Content-Type":"application/json"
},

body:JSON.stringify({
email,
password
})

});

const data=
await res.json();

alert(data.message);

if(data.message==="success")
{
window.location=
"dashboard.html";
}
}

